export function formatCurrency(amountTHB: number, currency: Currency): string {
  const cfg = CURRENCIES[currency];
  const converted = amountTHB * cfg.rateFromTHB;
  if (currency === 'JPY' || currency === 'THB') {
    return `${cfg.symbol}${Math.round(converted).toLocaleString()}`;
  }
  return `${cfg.symbol}${converted.toFixed(2)}`;
}
